"""
End-to-end integration test: reads a real pcap file (containing the
RFC 9369 Appendix A.2 sample packet wrapped in Ethernet/IP/UDP
headers, generated by tests/data/generate_vectors.py) through the
full capture -> flow-tracking -> Initial-decrypt -> ClientHello-parse
pipeline, exercising the same code path the CLI's `analyze` command
uses.
"""

from pathlib import Path

import pytest

from quicfp.capture import analyze_pcap
from quicfp.features import extract_features
from quicfp.fingerprint import compute_fingerprint
from quicfp.headers import QUIC_VERSION_2

PCAP_PATH = Path(__file__).parent / "data" / "rfc9369_client_initial.pcap"


@pytest.mark.skipif(not PCAP_PATH.exists(), reason="test pcap not generated")
def test_analyze_pcap_recovers_clienthello():
    table = analyze_pcap(str(PCAP_PATH))
    flows = table.flows()

    assert len(flows) == 1
    flow = flows[0]

    assert flow.version == QUIC_VERSION_2
    assert flow.client_hello_parsed
    assert flow.client_hello is not None
    assert flow.client_hello.sni == "example.com"
    assert flow.parse_error is None


@pytest.mark.skipif(not PCAP_PATH.exists(), reason="test pcap not generated")
def test_analyze_pcap_produces_stable_fingerprint():
    table = analyze_pcap(str(PCAP_PATH))
    flow = table.flows()[0]

    fp1 = compute_fingerprint(flow.client_hello, quic_version_is_v2=True)
    fp2 = compute_fingerprint(flow.client_hello, quic_version_is_v2=True)
    assert fp1.sorted_fingerprint == fp2.sorted_fingerprint
    assert len(fp1.sorted_fingerprint) == 64  # sha256 hex digest


@pytest.mark.skipif(not PCAP_PATH.exists(), reason="test pcap not generated")
def test_single_packet_flow_has_no_statistical_features():
    # A flow containing only one Initial packet is too short for
    # meaningful statistical features (see extract_features' packet_count
    # >= 2 threshold) -- this documents that boundary rather than
    # asserting a fabricated non-empty result.
    table = analyze_pcap(str(PCAP_PATH))
    flow = table.flows()[0]
    feats = extract_features(flow)
    assert feats is None
